"""
ChimeraX export — paint per-residue results onto structures.

WHY THIS IS CHEAP TO BUILD HERE
The hard part of "plot MD results onto a structure" is mapping GROMACS' flat,
chainless residue numbering back to biological identity (chain + full-length
residue number). system_map.py already does that in the forward direction for
selections; this module adds the INVERSE (flat -> chain/resnum) and formats the
result as a ChimeraX attribute assignment file.

DATA PATH
  1. Write a .defattr file assigning a numeric attribute to residues.
  2. Write a .cxc command script that opens the structure, applies the
     attribute, colours by it, and optionally saves a high-resolution image.
  3. Either hand those files to the user, or POST commands to a running
     ChimeraX instance via its REST remote-control server.

FORMAT NOTE (the thing everyone gets wrong)
Attribute assignment files are whitespace-sensitive: the residue spec and its
value must be separated by a TAB, not spaces. We emit tabs explicitly.

SAFETY NOTE
Exporting a mis-numbered figure is worse than exporting none, because the error
is invisible in the final image. When the session has a system definition with
a cached residue-identity table, we verify the residue NAME at each position
before writing, and refuse the export on mismatch rather than producing a
subtly wrong figure.
"""

import logging
import re
import shutil
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Optional

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel

from .gmx import get_cached_result
from .session import ChainDef, load_state, session_dir
from .system_map import chain_offsets

log = logging.getLogger("gromax.chimerax")

router = APIRouter()


# ─── Inverse mapping: flat residue index -> biological identity ───────────────

def flat_to_bio(chains: list[ChainDef], flat: int) -> Optional[tuple[str, int]]:
    """
    Map a flat 1-based residue index back to (chain_id, full-length resnum).

    The inverse of system_map.bio_to_flat. Returns None if the index falls
    outside every defined chain, which means the system definition doesn't
    describe the thing that was analysed — worth surfacing rather than guessing.
    """
    offsets = chain_offsets(chains)
    for c in chains:
        n = c.n_residues if c.n_residues else (c.end_resnum - c.start_resnum + 1)
        start = offsets[c.id] + 1
        if start <= flat < start + n:
            return (c.id, c.start_resnum + (flat - start))
    return None


# ─── defattr writing ──────────────────────────────────────────────────────────

def _safe_attr_name(name: str) -> str:
    """
    ChimeraX attribute names must be identifier-like. Also avoid a leading
    digit and keep it recognisably ours.
    """
    cleaned = re.sub(r"[^A-Za-z0-9_]", "", name.replace(" ", "_").replace("-", "_"))
    if not cleaned:
        cleaned = "value"
    if cleaned[0].isdigit():
        cleaned = f"v{cleaned}"
    return f"gromax{cleaned[0].upper()}{cleaned[1:]}"


def build_defattr(
    values: list[float],
    attr_name: str,
    chains: Optional[list[ChainDef]] = None,
    residue_numbers: Optional[list[int]] = None,
) -> str:
    """
    Build attribute-assignment-file text.

    `values[i]` corresponds to residue_numbers[i] if given, else to flat index
    i+1. With `chains`, specs are written as /CHAIN:RESNUM; without, as
    :RESNUM (single-chain / already-biological numbering).
    """
    lines = [
        f"# Generated by GroMax GUI",
        f"attribute: {attr_name}",
        "match mode: 1-to-1",
        "recipient: residues",
    ]

    n_mapped = 0
    n_unmapped = 0
    for i, val in enumerate(values):
        if val is None:
            continue
        flat = residue_numbers[i] if residue_numbers else (i + 1)
        try:
            flat = int(flat)
        except (TypeError, ValueError):
            continue

        if chains:
            bio = flat_to_bio(chains, flat)
            if bio is None:
                n_unmapped += 1
                continue
            chain_id, resnum = bio
            spec = f"/{chain_id}:{resnum}"
        else:
            spec = f":{flat}"

        # TAB separated — spaces silently fail to parse in ChimeraX.
        lines.append(f"\t{spec}\t{float(val):.6g}")
        n_mapped += 1

    if n_unmapped:
        lines.insert(1, f"# WARNING: {n_unmapped} residue(s) fell outside the "
                        f"defined chains and were skipped")
    if not n_mapped:
        raise ValueError(
            "No residues could be mapped. Check that the system definition "
            "matches the analysed structure."
        )
    return "\n".join(lines) + "\n"


def build_cxc(
    structure_path: str,
    defattr_path: str,
    attr_name: str,
    palette: str = "^RdYlBu",
    representation: str = "cartoon",
    image_path: Optional[str] = None,
    image_width: int = 2000,
) -> str:
    """
    Build a ChimeraX command script.

    Kept deliberately readable: users tweak these by hand for figures, and an
    unreadable generated script gets thrown away.
    """
    lines = [
        "# Generated by GroMax GUI — edit freely, this is just a starting point.",
        "",
        f"open {structure_path}",
        f"open {defattr_path}",
        "",
        "hide atoms",
        "show cartoons",
        f"color byattribute {attr_name} palette {palette}",
    ]

    if representation == "worm":
        lines.append(
            f"cartoon byattribute {attr_name}   # worm radius tracks the value")

    lines += [
        "",
        "# Colour key for the figure legend",
        f"key {palette} :start :end",
        "",
        "set bgColor white",
        "lighting soft",
        "graphics silhouettes true",
    ]

    if image_path:
        lines += [
            "",
            f"save {image_path} width {image_width} supersample 3 "
            f"transparentBackground true",
        ]

    return "\n".join(lines) + "\n"


# ─── Talking to a running ChimeraX ────────────────────────────────────────────

def send_to_chimerax(command: str, port: int, host: str = "127.0.0.1",
                     timeout: float = 15.0) -> dict:
    """
    Send one command to a running ChimeraX REST server.

    The user starts it once with:
        remotecontrol rest start port <N> json true

    (This can be made permanent in ChimeraX Preferences -> Startup.)
    """
    url = f"http://{host}:{port}/run?{urllib.parse.urlencode({'command': command})}"
    try:
        with urllib.request.urlopen(url, timeout=timeout) as resp:
            body = resp.read().decode("utf-8", errors="replace")
        return {"ok": True, "response": body[:4000]}
    except urllib.error.URLError as e:
        return {
            "ok": False,
            "error": (
                f"Could not reach ChimeraX on {host}:{port} ({e}). "
                f"In ChimeraX run:  remotecontrol rest start port {port} json true"
            ),
        }
    except Exception as e:  # noqa: BLE001 - surface anything else verbatim
        return {"ok": False, "error": str(e)}


# ─── Request models ───────────────────────────────────────────────────────────

class ExportRequest(BaseModel):
    session_id: str
    cache_key: str                     # which stored analysis to export
    structure_path: Optional[str] = None   # defaults to the condition's PDB
    attr_name: Optional[str] = None
    palette: str = "^RdYlBu"
    representation: str = "cartoon"    # or "worm"
    save_image: bool = False
    image_width: int = 2000
    use_system_definition: bool = True


class SendRequest(BaseModel):
    session_id: str
    cache_key: str
    port: int = 60958
    host: str = "127.0.0.1"
    structure_path: Optional[str] = None
    palette: str = "^RdYlBu"
    representation: str = "cartoon"


class PingRequest(BaseModel):
    port: int = 60958
    host: str = "127.0.0.1"


# ─── Helpers ──────────────────────────────────────────────────────────────────

def _per_residue_series(result: dict) -> tuple[list[float], Optional[list[int]]]:
    """
    Pull a per-residue series out of a stored analysis result.

    Only per-residue analyses make sense on a structure: RMSF gives one value
    per residue, contact/H-bond occupancy likewise. A per-FRAME series (RMSD vs
    time) does not map onto residues at all, so we reject it explicitly rather
    than producing a meaningless figure.
    """
    kind = result.get("kind")
    if kind not in ("line", "contacts", None):
        raise HTTPException(
            status_code=400,
            detail=f"'{kind}' results can't be mapped onto residues. "
                   f"Use a per-residue analysis such as RMSF or contact occupancy.",
        )

    xlabel = (result.get("xlabel") or "").lower()
    if "time" in xlabel:
        raise HTTPException(
            status_code=400,
            detail="This analysis is per-frame (x axis is time), so it has no "
                   "per-residue value to paint onto a structure. Use RMSF, "
                   "contact occupancy, or another per-residue metric.",
        )

    y = result.get("y_mean") or result.get("y") or []
    x = result.get("x") or []
    if not y:
        raise HTTPException(status_code=400, detail="Result contains no values.")

    resnums = None
    if x and len(x) == len(y):
        try:
            resnums = [int(round(float(v))) for v in x]
        except (TypeError, ValueError):
            resnums = None
    return list(y), resnums


def _resolve_structure(state, result: dict, override: Optional[str]) -> str:
    if override:
        return override
    cond_id = result.get("condition_id")
    cond = (state.conditions or {}).get(cond_id)
    if cond and cond.pdb:
        return cond.pdb
    raise HTTPException(
        status_code=400,
        detail="No reference structure for this condition. Register a PDB, or "
               "pass structure_path explicitly.",
    )


def _chains_for(state, use_system_definition: bool) -> Optional[list[ChainDef]]:
    if not use_system_definition:
        return None
    sd = state.system_definition
    if sd and sd.chains:
        return sd.chains
    return None


# ─── Routes ───────────────────────────────────────────────────────────────────

@router.post("/export")
def export_files(req: ExportRequest):
    """
    Write a .defattr + .cxc pair next to the analysis results.

    This is the zero-dependency path: it works whether or not ChimeraX is
    installed or running. The user opens the .cxc in ChimeraX.
    """
    state = load_state(req.session_id)
    result = get_cached_result(req.session_id, req.cache_key)
    if result is None:
        raise HTTPException(status_code=404, detail="Result not cached")

    values, resnums = _per_residue_series(result)
    structure = _resolve_structure(state, result, req.structure_path)
    chains = _chains_for(state, req.use_system_definition)

    analysis_name = result.get("analysis_name") or result.get("analysis_type") or "value"
    attr = _safe_attr_name(req.attr_name or analysis_name)

    out_dir = session_dir(req.session_id) / "chimerax"
    out_dir.mkdir(parents=True, exist_ok=True)

    cond = (result.get("condition_name") or "cond").replace(" ", "-")
    stem = re.sub(r"[^A-Za-z0-9_\-]", "", f"{analysis_name}_{cond}") or "gromax"

    defattr_path = out_dir / f"{stem}.defattr"
    cxc_path = out_dir / f"{stem}.cxc"
    image_path = str(out_dir / f"{stem}.png") if req.save_image else None

    try:
        defattr_path.write_text(build_defattr(values, attr, chains, resnums))
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))

    cxc_path.write_text(build_cxc(
        structure_path=structure,
        defattr_path=str(defattr_path),
        attr_name=attr,
        palette=req.palette,
        representation=req.representation,
        image_path=image_path,
        image_width=req.image_width,
    ))

    return {
        "ok": True,
        "attribute": attr,
        "defattr": str(defattr_path),
        "cxc": str(cxc_path),
        "image": image_path,
        "n_residues": len(values),
        "mapped_with_chains": bool(chains),
        "structure": structure,
        "hint": f"In ChimeraX:  open {cxc_path}",
    }


@router.post("/send")
def send_live(req: SendRequest):
    """Push the colouring straight into a running ChimeraX via REST."""
    export = export_files(ExportRequest(
        session_id=req.session_id,
        cache_key=req.cache_key,
        structure_path=req.structure_path,
        palette=req.palette,
        representation=req.representation,
    ))
    res = send_to_chimerax(f"open {export['cxc']}", port=req.port, host=req.host)
    return {**export, "sent": res["ok"], "chimerax": res}


@router.post("/ping")
def ping(req: PingRequest):
    """Check whether a ChimeraX REST server is listening."""
    res = send_to_chimerax("version", port=req.port, host=req.host, timeout=4.0)
    return {"available": res["ok"], **res}


@router.get("/detect")
def detect():
    """
    Look for a ChimeraX executable, so the UI can offer to launch it.

    ChimeraX is NOT bundled — same reasoning as GROMACS: it's large, and users
    have their own installation they want used.
    """
    candidates = ["ChimeraX", "chimerax"]
    for name in candidates:
        found = shutil.which(name)
        if found:
            return {"found": True, "path": found}

    guesses = []
    if sys.platform == "darwin":
        guesses = ["/Applications/ChimeraX.app/Contents/MacOS/ChimeraX"]
    elif sys.platform.startswith("win"):
        guesses = [r"C:\Program Files\ChimeraX\bin\ChimeraX.exe"]
    elif sys.platform.startswith("linux"):
        guesses = ["/usr/bin/chimerax", "/usr/local/bin/chimerax",
                   "/opt/UCSF/ChimeraX/bin/ChimeraX"]
    for g in guesses:
        if Path(g).exists():
            return {"found": True, "path": g}

    return {
        "found": False,
        "path": None,
        "hint": "ChimeraX not found on PATH. Install it from "
                "https://www.rbvi.ucsf.edu/chimerax/ or set the path manually.",
    }
